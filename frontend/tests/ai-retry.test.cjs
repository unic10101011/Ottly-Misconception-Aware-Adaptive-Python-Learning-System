const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Module = require('node:module')
const React = require('react')
const { transformSync } = require('esbuild')
const { renderToStaticMarkup } = require('react-dom/server')

test('retry distinguishes timeout, network and rejected content and disables pending actions', () => {
  const filename = path.resolve(__dirname, '../src/components/AiRetry.jsx')
  assert.ok(fs.existsSync(filename), 'shared retry component must exist')
  const loaded = new Module(filename, module)
  loaded.filename = filename; loaded.paths = Module._nodeModulePaths(path.dirname(filename))
  loaded._compile(transformSync(fs.readFileSync(filename, 'utf8'), { loader: 'jsx', format: 'cjs' }).code, filename)
  const Retry = loaded.exports.default
  const html = props => renderToStaticMarkup(React.createElement(Retry, { onRetry() {}, ...props }))
  assert.match(html({ status: 'timeout' }), /生成超时/)
  assert.match(html({ message: 'Failed to fetch' }), /连接失败/)
  assert.match(html({ status: 'invalid_response' }), /本次回答未能生成/)
  assert.doesNotMatch(html({ status: 'invalid_response' }), /网络错误/)
  assert.match(html({ pending: true }), /disabled/)
  assert.match(html({ pending: true }), /aria-busy="true"/)
})
